// Generates out/sw.js after `next build`: precaches every static file of the export (content-hashed
// names, so the cache key changes whenever the build does) and caches map tiles as you browse.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const BASE = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
const SKIP = /(\.map$|\.txt$|^sw\.js$|^data\/opera-disp-points\.json$|^frames\/|__next\.|_not-found|404)/;

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const files = walk(OUT).map((p) => relative(OUT, p).split(sep).join("/")).filter((f) => !SKIP.test(f)).sort();
const hash = createHash("sha256");
for (const f of files) hash.update(f).update(readFileSync(join(OUT, f)));
const version = hash.digest("hex").slice(0, 12);
// pre-rendered globe pictures (npm run frames): cached as they are viewed, in a cache named after their manifests so a re-capture replaces them
const fh = createHash("sha256");
for (const f of walk(OUT).filter((p) => /frames[\\/](desktop|mobile)[\\/]manifest\.json$/.test(p)).sort()) fh.update(readFileSync(f));
const framesKey = fh.digest("hex").slice(0, 10);
const urls = files.map((f) => `${BASE}/${f.replace(/index\.html$/, "")}`);

const sw = `/* Generated by scripts/build-sw.mjs; do not edit. */
const VERSION = "sarpulse-${version}";
const TILES = "sarpulse-tiles-v3";
const TILE_LIMIT = 4000;
const FRAMES = "sarpulse-frames-${framesKey}";
// tile and glyph files never change under their URL; TileJSON (e.g. /planet) points at the current tile version, so it must stay fresh
const IMMUTABLE = /(\\/\\d+\\/\\d+\\/\\d+(\\.[a-z]+)?$|\\/\\d+-\\d+\\.pbf$|\\/tile\\/\\d+\\/\\d+\\/\\d+$)/;
const PRECACHE = ${JSON.stringify(urls)};
const TILE_HOSTS = /(elevation-tiles-prod\\.s3\\.amazonaws\\.com|server\\.arcgisonline\\.com|tiles\\.openfreemap\\.org|gibs(-[abc])?\\.earthdata\\.nasa\\.gov)$/;

self.addEventListener("install", (e) => e.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())));
self.addEventListener("activate", (e) => e.waitUntil(
  caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== VERSION && k !== TILES && k !== FRAMES).map((k) => caches.delete(k)))).then(() => self.clients.claim())
));
async function trim(cache) {
  const keys = await cache.keys();
  if (keys.length > TILE_LIMIT) await Promise.all(keys.slice(0, keys.length - TILE_LIMIT).map((k) => cache.delete(k)));
}
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (TILE_HOSTS.test(url.hostname)) {
    e.respondWith(caches.open(TILES).then(async (cache) => {
      const keep = (res) => { if (res.ok) { cache.put(req, res.clone()); trim(cache); } return res; };
      if (IMMUTABLE.test(url.pathname)) return (await cache.match(req)) || fetch(req).then(keep);
      // TileJSON: answer from cache at once and refresh in the background, so the map never waits on the network
      const hit = await cache.match(req);
      const fresh = fetch(req).then(keep).catch(() => hit || Response.error());
      return hit || fresh;
    }));
    return;
  }
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("${BASE}/frames/") && !url.pathname.endsWith("manifest.json")) {
    e.respondWith(caches.open(FRAMES).then(async (c) => (await c.match(req)) || fetch(req).then((r) => { if (r.ok) c.put(req, r.clone()); return r; })));
    return;
  }
  if (req.mode === "navigate") {
    // pages are precached together with their own scripts, so answering from the cache is instant and consistent;
    // a new deploy installs a new cache that takes over on the next visit
    e.respondWith(caches.match(req).then((r) => r || fetch(req)).catch(() => caches.match("${BASE}/")).then((r) => r || Response.error()));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached, version ${version}`);
